#!/bin/bash
# Кладёт в Lori QA набор записей для снимков экрана записи — в тех состояниях,
# которые можно показать без сети, без ключей и без моделей:
#
#   «Совещание по бюджету»   — текст, говорящие, заголовок и описание модели;
#   «Созвон с подрядчиком»   — длинный заголовок, заданный руками, и замечание о пропуске;
#   «Заметки после встречи»  — «Причёсанный текст» без таймкодов;
#   «Интервью с дизайнером»  — аудио без расшифровки;
#   «Звонок в банк»          — аудио; ошибку даёт сам тест, расшифровав его облачным
#                              движком без ключа (`TranscriptScreenUITests`);
#   «Лекция по истории»      — расшифровка прервана (облачная запись старого формата
#                              очереди, без снимка настроек: сама она не поднимается).
#
# Набор живёт в отдельном корне `Documents/Lori/RecoveryProbe`: только там рядом с
# записями можно положить свои `summaries.json` (заголовки и описания) и `queue.json`
# (очередь и обрывы) — приложение берёт их оттуда, когда запущено с `--recovery-probe`
# (только QA-сборка, см. `RecoveryProbe`). Рабочая папка QA не трогается, файлы
# только добавляются (`design/qa/safe-container.py`). Очередь и расшифровки в этих
# состояниях не запускаются: `input.wav`, по которому работает сама проба, здесь нет.
#
#   ./design/redesign-2026-10-05/seed-record-states.sh <explicit-simulator-uuid>
#
# Очередь и идущую расшифровку так не показать — для них нужен подставной движок.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
UDID="${1:?укажи UUID тестового симулятора Lori QA}"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
DEST="$WORK/seed"
mkdir -p "$DEST/Transcripts"

voice() {
  say -v Milena -o "$WORK/voice.aiff" "$2"
  afconvert -f m4af -d aac "$WORK/voice.aiff" "$DEST/$1.m4a"
}

voice "Совещание по бюджету" "Давайте начнём. Сегодня два вопроса: перенос релиза и бюджет на четвёртый квартал. По релизу предлагаю сдвинуть на две недели, иначе не успеем с оплатой и с проверкой на телефонах. Согласен. Тогда бюджет пересчитываем под новую дату, смету согласует Лёша до пятницы. Хорошо, я пришлю ему цифры сегодня вечером."
cat > "$DEST/Transcripts/Совещание по бюджету.md" <<'MD'
# Совещание по бюджету

_Расшифровано: ElevenLabs · scribe_v2_

_Режим: Дословно_

**[0:00–0:07]** S1: Давайте начнём. Сегодня два вопроса: перенос релиза и бюджет на четвёртый квартал.

**[0:07–0:14]** S2: По релизу предлагаю сдвинуть на две недели, иначе не успеем с оплатой и с проверкой на телефонах.

**[0:14–0:21]** S1: Согласен. Тогда бюджет пересчитываем под новую дату, смету согласует Лёша до пятницы.

**[0:21–0:25]** S2: Хорошо, я пришлю ему цифры сегодня вечером.
MD

voice "Созвон с подрядчиком" "Подрядчик просит ещё две недели на второй этап. Правки сверх договора предлагаю оплачивать пополам. Решение пришлём письмом до среды."
cat > "$DEST/Transcripts/Созвон с подрядчиком.md" <<'MD'
# Созвон с подрядчиком

_Расшифровано: GigaAM v3 CTC (int8), на этом iPhone_

**[0:00–0:04]** Подрядчик просит ещё две недели на второй этап.

**[0:04–0:08]** Правки сверх договора предлагаю оплачивать пополам.

**[0:08–0:11]** Решение пришлём письмом до среды.

> Пропуск 0:11–0:12: слов для этого участка сервис не дал
MD

voice "Заметки после встречи" "Главное со встречи: клиент хочет запуск в ноябре, бюджет не меняется, дизайн утверждают в понедельник."
cat > "$DEST/Transcripts/Заметки после встречи.md" <<'MD'
# Заметки после встречи

_Расшифровано: Gemini · gemini-3.5-transcribe_

_Режим: Причёсанный текст_

Главное со встречи: клиент хочет запуск в ноябре, бюджет не меняется, дизайн утверждают в понедельник. Отдельно обсудили, кто готовит презентацию для совета: её делает команда продукта, а цифры по продажам присылает финансовый отдел до четверга. Если цифры задержатся, презентацию переносим на следующую неделю, а совету отправляем короткое письмо с текущим состоянием.
MD

voice "Интервью с дизайнером" "Расскажите, с чего начинается ваш рабочий день и как вы выбираете, за какую задачу взяться первой."
voice "Звонок в банк" "Здравствуйте, я хотел бы уточнить статус перевода, отправленного в пятницу."
voice "Лекция по истории" "Сегодня мы поговорим о том, как менялись торговые пути в Средиземноморье."

# Заголовки: от модели — с описанием; заданный руками — длинный, чтобы видеть
# предел в три строки Georgia.
cat > "$DEST/summaries.json" <<'JSON'
{
  "Совещание по бюджету.m4a": {
    "title": "Совещание по бюджету",
    "detail": "Обсудили перенос релиза на две недели и бюджет четвёртого квартала; смету Лёша согласует до пятницы.",
    "manual": false, "origin": "generated", "summarized": true, "stale": false, "replaceManual": false
  },
  "Созвон с подрядчиком.m4a": {
    "title": "Созвон с подрядчиком о переносе сроков второго этапа и о том, кто платит за дополнительные правки макетов",
    "detail": "Подрядчик просит две недели; правки сверх договора делим пополам, решение — письмом до среды.",
    "manual": true, "origin": "manual", "summarized": true, "stale": false, "replaceManual": false
  }
}
JSON

# Обрыв облачной расшифровки в старом формате очереди — только движок, без снимка
# настроек: такую запись `resumeInterrupted` сам не поднимает, и пометка стоит.
cat > "$DEST/queue.json" <<'JSON'
{"jobs": {}, "legacy": {"Лекция по истории.m4a": "elevenlabs"}}
JSON

python3 "$SCRIPT_DIR/../qa/safe-container.py" "$UDID" "$DEST" Documents/Lori/RecoveryProbe
